// src/app/api/pdf/receipt/route.ts
import { NextResponse } from 'next/server';
import { SchoolService } from '@/lib/services/schoolService';

export async function GET(request: Request) {
  const { searchParams } = new URL(request.url);
  const paymentId = searchParams.get('payment_id');
  const payments = SchoolService.getPayments();
  const payment = payments.find((p) => p.id === paymentId) || payments[0];
  const school = SchoolService.getSchoolInfo();
  const student = SchoolService.getStudentById(payment?.student_id || 'stu_gabriel');

  const html = `
    <!DOCTYPE html>
    <html lang="en">
    <head>
      <meta charset="UTF-8">
      <title>Official Receipt - ${payment?.receipt_number}</title>
      <style>
        body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Arial, sans-serif; padding: 40px; color: #0f172a; max-width: 650px; margin: 0 auto; }
        .receipt-card { border: 2px solid #0f172a; border-radius: 8px; padding: 30px; position: relative; }
        .header { text-align: center; border-bottom: 2px dashed #cbd5e1; padding-bottom: 20px; margin-bottom: 20px; }
        .school-name { font-size: 18px; font-weight: 800; text-transform: uppercase; }
        .title { font-size: 14px; font-weight: 700; margin-top: 10px; color: #059669; letter-spacing: 1px; }
        .or-number { position: absolute; top: 30px; right: 30px; font-family: monospace; font-size: 14px; font-weight: 700; color: #e11d48; }
        .info-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; font-size: 13px; margin-bottom: 20px; }
        .amount-box { background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 15px; margin: 20px 0; text-align: center; }
        .amount-val { font-size: 24px; font-weight: 800; font-family: monospace; color: #0f172a; }
        .footer { margin-top: 30px; font-size: 11px; text-align: center; color: #64748b; border-top: 1px solid #e2e8f0; padding-top: 15px; }
        .print-btn { background: #0f172a; color: white; border: none; padding: 8px 16px; border-radius: 6px; cursor: pointer; font-weight: 600; margin-bottom: 20px; }
        @media print { .print-btn { display: none; } }
      </style>
    </head>
    <body>
      <button class="print-btn" onclick="window.print()">Print Receipt</button>

      <div class="receipt-card">
        <div class="or-number">${payment?.receipt_number}</div>

        <div class="header">
          <div class="school-name">${school.name}</div>
          <div style="font-size: 11px; color: #64748b; margin-top: 4px;">${school.address}</div>
          <div class="title">OFFICIAL PAYMENT RECEIPT</div>
        </div>

        <div class="info-grid">
          <div><strong>Date:</strong> ${new Date(payment?.created_at || '').toLocaleDateString('en-PH')}</div>
          <div><strong>Payment Mode:</strong> ${payment?.payment_method?.toUpperCase()}</div>
          <div><strong>Student Name:</strong> ${student?.user?.first_name} ${student?.user?.last_name}</div>
          <div><strong>LRN:</strong> ${student?.lrn}</div>
          <div><strong>Transaction Ref:</strong> ${payment?.transaction_reference}</div>
          <div><strong>Particulars:</strong> ${payment?.notes || 'Tuition Fee Payment'}</div>
        </div>

        <div class="amount-box">
          <div style="font-size: 11px; text-transform: uppercase; color: #64748b; font-weight: 600;">Amount Received</div>
          <div class="amount-val">₱ ${payment?.amount?.toLocaleString()}.00</div>
          <div style="font-size: 11px; color: #059669; font-weight: 600; margin-top: 4px;">Payment Completed • Balanced in Student Ledger</div>
        </div>

        <div class="footer">
          <div>This is an official electronic receipt generated by the School Finance Management System.</div>
          <div style="margin-top: 4px;">Philippine Science & Arts Academy Cashier Office</div>
        </div>
      </div>
    </body>
    </html>
  `;

  return new NextResponse(html, {
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
    },
  });
}
